from datetime import date
from typing import Any

from fastapi import APIRouter, Request
from pydantic import BaseModel, Field

from app.config import get_settings
from app.deps import DB, CtxDep
from app.errors import api_error
from app.security.ratelimit import enforce
from app.services import commands as cmd
from app.services import planning
from app.services.audit import audit
from app.services.owned import active_transition

router = APIRouter(tags=["natural-language commands"])


class InterpretIn(BaseModel):
    text: str = Field(min_length=2, max_length=2000)


class ExecuteIn(BaseModel):
    type: str
    params: dict[str, Any]
    confirmed: bool = False


@router.post("/commands/interpret")
def interpret(body: InterpretIn, request: Request, db: DB, ctx: CtxDep) -> dict:
    """Step 1-4: accept dictated text, parse it, validate it, return the proposed change."""
    enforce(request, "ai", get_settings().rate_limit_ai_per_minute, subject=ctx.workspace_id)
    proposal = cmd.parse_rules(body.text)
    method = "rules"
    if proposal is None and get_settings().provider_for("command_parsing") != "rules":
        proposal = cmd.interpret_ai(db, workspace_id=ctx.workspace_id, is_guest=ctx.is_guest, text=body.text)
        method = "ai"
    db.commit()
    if proposal is None:
        return {"understood": False, "message": "I could not turn that into an action. Try e.g. \"I can study 8 hours a week\", "
                "\"my deadline is June 30\", \"I finished today's task\" or \"I applied for a data analyst role at Acme\".",
                "text": body.text}
    v = cmd.validate(db, ctx.workspace_id, proposal)
    return {"understood": True, "method": method, "text": body.text, "action": {"type": proposal.type, "params": proposal.params},
            "requires_confirmation": v["consequential"], **v}


@router.post("/commands/execute")
def execute(body: ExecuteIn, request: Request, db: DB, ctx: CtxDep) -> dict:
    """Steps 5-7: re-validate, require confirmation for consequential changes, execute, report the real result."""
    p = cmd.Proposal(type=body.type, params=dict(body.params))
    v = cmd.validate(db, ctx.workspace_id, p)
    if not v["valid"]:
        raise api_error(422, "INVALID_ACTION", "; ".join(v["errors"]))
    if v["consequential"] and not body.confirmed:
        raise api_error(409, "CONFIRMATION_REQUIRED", "Please confirm this change first.")
    prm = p.params
    result: dict[str, Any] = {}
    if p.type in ("set_weekly_hours", "set_deadline", "set_budget", "set_target_role"):
        t = active_transition(db, ctx.workspace_id)
        if p.type == "set_weekly_hours":
            t.weekly_hours = float(prm["hours"])
        elif p.type == "set_deadline":
            t.deadline = date.fromisoformat(prm["deadline"])
        elif p.type == "set_budget":
            t.budget_amount = float(prm["amount"])
            t.budget_currency = (prm.get("currency") or t.budget_currency).upper()
        else:
            t.target_role = prm["role"]
        t.version += 1
        result = {"transition": {"weekly_hours": t.weekly_hours, "deadline": t.deadline.isoformat() if t.deadline else None,
                                 "budget_amount": t.budget_amount, "budget_currency": t.budget_currency, "target_role": t.target_role},
                  "hint": "Regenerate your plan to apply this change to the schedule." if p.type != "set_target_role"
                  else "Add a job description for the new role to update your analysis."}
    elif p.type == "complete_task":
        from app.api.v1.plans import TaskPatch, update_task

        result = {"task": update_task(prm["task_id"], TaskPatch(status="completed"), db, ctx)}
    elif p.type == "add_application":
        from app.api.v1.tracking import ApplicationIn, application_out, create_application

        a = create_application(db, ctx, ApplicationIn(company=prm["company"], role_title=prm["role_title"], status=prm.get("status", "applied")))
        result = {"application": application_out(db, a)}
    elif p.type == "update_application_status":
        from app.api.v1.tracking import ApplicationPatch, patch_application

        result = {"application": patch_application(prm["application_id"], ApplicationPatch(status=prm["status"]), db, ctx)}
    elif p.type == "start_topic_check":
        from app.api.v1.assessments import StartIn, start

        t = active_transition(db, ctx.workspace_id)
        result = {"assessment": start(t.id, StartIn(kind="topic_check", skill_id=prm["skill_id"]), request, db, ctx)}
    elif p.type == "regenerate_plan":
        t = active_transition(db, ctx.workspace_id)
        version = planning.build_plan(db, t, reason="Regenerated by voice/text command")
        result = {"plan_version": version.version_number, "status": version.status}
    audit(db, action="command.executed", workspace_id=ctx.workspace_id, actor=ctx.actor, details={"type": p.type})
    db.commit()
    return {"ok": True, "type": p.type, "summary": v["summary"], "result": result}
