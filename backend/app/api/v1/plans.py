@router.get("/transitions/{transition_id}/resources")
def recommendations(transition_id: str, db: DB, ctx: CtxDep) -> dict:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    recs = list(db.scalars(select(ResourceRecommendation).where(ResourceRecommendation.transition_id == t.id)
                           .order_by(ResourceRecommendation.skill_id, ResourceRecommendation.rank)))
    groups: dict[str, list] = {}
    for r in recs:
        res = db.get(LearningResource, r.resource_id)
        groups.setdefault(r.skill_id, []).append({**res_svc.resource_out(res), "rank": r.rank, "score": r.score,  # type: ignore[arg-type]
                                                  "rationale": r.rationale, "ranking_method": r.ranking_method})
    return {"groups": [{"skill_id": k, "items": v} for k, v in groups.items()], "discovery": res_svc.discovery_status()}


@router.post("/transitions/{transition_id}/resources/refresh")
def refresh(transition_id: str, request: Request, db: DB, ctx: CtxDep) -> dict:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    enforce(request, "ai", get_settings().rate_limit_ai_per_minute, subject=ctx.workspace_id)
    res_svc.recommend(db, t, skill_gaps(db, t)["items"])
    db.commit()
    return recommendations(transition_id, db, ctx)


@router.get("/resources")
def catalogue(db: DB, ctx: CtxDep, skill: str | None = None) -> list[dict]:
    rows = db.scalars(select(LearningResource).order_by(LearningResource.title))
    return [res_svc.resource_out(r) for r in rows if not skill or skill in r.skills]


@router.post("/resources/{resource_id}/verify")
def verify(resource_id: str, request: Request, db: DB, ctx: CtxDep) -> dict:
    enforce(request, "verify", 10, subject=ctx.workspace_id)
    r = db.get(LearningResource, resource_id)
    if not r:
        raise api_error(404, "NOT_FOUND", "Resource not found.")
    res_svc.verify_resource(r)
    db.commit()
    return res_svc.resource_out(r)


