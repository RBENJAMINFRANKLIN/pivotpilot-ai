router = APIRouter(tags=["learning plan"])


def task_out(x: PlanTask, resources: dict[str, LearningResource]) -> dict:
    r = resources.get(x.resource_id) if x.resource_id else None
    return {"id": x.id, "week": x.week_number, "day": x.day_number, "date": x.scheduled_date.isoformat(), "skill_id": x.skill_id,
            "type": x.task_type, "title": x.title, "description": x.description, "minutes": x.estimated_minutes, "status": x.status,
            "criteria": x.completion_criteria, "rationale": x.rationale, "project_id": x.project_id, "version": x.version,
            "carried_over": x.carried_from_task_id is not None, "completed_at": x.completed_at.isoformat() if x.completed_at else None,
            "resource": {"title": r.title, "url": r.canonical_url, "provider": r.provider,
                         "verification_status": res_svc.effective_status(r)} if r else None}


def version_out(db, v: LearningPlanVersion, plan: LearningPlan) -> dict:
    tasks = list(db.scalars(select(PlanTask).where(PlanTask.plan_version_id == v.id).order_by(PlanTask.week_number, PlanTask.day_number, PlanTask.id)))
    res_ids = {x.resource_id for x in tasks if x.resource_id}
    resources = {r.id: r for r in db.scalars(select(LearningResource).where(LearningResource.id.in_(res_ids)))} if res_ids else {}
    scheduled = [x for x in tasks if x.week_number > 0]
    done = sum(x.estimated_minutes for x in scheduled if x.status == "completed")
    total = sum(x.estimated_minutes for x in scheduled)
    return {"plan_id": plan.id, "plan_status": plan.status, "version_id": v.id, "version": v.version_number, "status": v.status,
            "reason": v.reason, "start_date": v.start_date.isoformat(), "summary": v.summary, "weeks": v.weeks,
            "feasibility": v.feasibility, "generation_method": v.generation_method, "created_at": v.created_at.isoformat(),
            "progress": {"completed_minutes": done, "total_minutes": total, "percent": round(100 * done / total, 1) if total else 0},
            "tasks": [task_out(x, resources) for x in tasks]}


class PlanIn(BaseModel):
    scope: Literal["full", "mandatory_only"] = "full"
    reason: str = Field(default="Generated by you", max_length=200)


@router.post("/transitions/{transition_id}/plan", status_code=201)
def generate(transition_id: str, body: PlanIn, db: DB, ctx: CtxDep) -> dict:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    v = planning.build_plan(db, t, scope=body.scope, reason=body.reason)
    audit(db, action="plan.generated", workspace_id=ctx.workspace_id, actor=ctx.actor, entity_type="plan_version", entity_id=v.id,
          details={"version": v.version_number, "status": v.status, "conflict": v.feasibility.get("conflict")})
    db.commit()
    return version_out(db, v, db.get(LearningPlan, v.plan_id))


@router.get("/transitions/{transition_id}/plan")
def current_plan(transition_id: str, db: DB, ctx: CtxDep) -> dict | None:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    plan = db.scalar(select(LearningPlan).where(LearningPlan.transition_id == t.id))
    if not plan or not plan.current_version_id:
        return None
    out = version_out(db, db.get(LearningPlanVersion, plan.current_version_id), plan)
    out["versions"] = [{"id": v.id, "version": v.version_number, "status": v.status, "reason": v.reason, "created_at": v.created_at.isoformat()}
                       for v in db.scalars(select(LearningPlanVersion).where(LearningPlanVersion.plan_id == plan.id).order_by(LearningPlanVersion.version_number.desc()))]
    return out


@router.get("/plan-versions/{version_id}")
def plan_version(version_id: str, db: DB, ctx: CtxDep) -> dict:
    v = get_owned(db, LearningPlanVersion, version_id, ctx.workspace_id, "Plan version")
    return version_out(db, v, db.get(LearningPlan, v.plan_id))


@router.post("/transitions/{transition_id}/plan/pause")
def pause(transition_id: str, db: DB, ctx: CtxDep) -> dict:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    plan = db.scalar(select(LearningPlan).where(LearningPlan.transition_id == t.id))
    if not plan:
        raise api_error(404, "NOT_FOUND", "No plan yet.")
    plan.status = "paused"
    db.commit()
    return {"status": "paused"}


@router.post("/transitions/{transition_id}/plan/resume", status_code=201)
def resume(transition_id: str, db: DB, ctx: CtxDep) -> dict:
    """Resuming reschedules the remaining work from today; completed work is kept."""
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    plan = db.scalar(select(LearningPlan).where(LearningPlan.transition_id == t.id))
    if not plan:
        raise api_error(404, "NOT_FOUND", "No plan yet.")
    cur = db.get(LearningPlanVersion, plan.current_version_id)
    v = planning.build_plan(db, t, scope=cur.summary.get("scope", "full"), reason="Resumed after a pause")  # type: ignore[union-attr]
    db.commit()
    return version_out(db, v, plan)


class TaskPatch(BaseModel):
    status: Literal["pending", "in_progress", "completed", "paused", "skipped"] | None = None
    scheduled_date: date | None = None
    minutes_spent: int | None = Field(default=None, ge=0, le=1440)
    note: str | None = Field(default=None, max_length=2000)
    version: int | None = None


@router.patch("/tasks/{task_id}")
def update_task(task_id: str, body: TaskPatch, db: DB, ctx: CtxDep) -> dict:
    x = get_owned(db, PlanTask, task_id, ctx.workspace_id, "Task")
    v = db.get(LearningPlanVersion, x.plan_version_id)
    plan = db.get(LearningPlan, v.plan_id)  # type: ignore[union-attr]
    if plan.current_version_id != v.id:  # type: ignore[union-attr]
        raise api_error(409, "OLD_VERSION", "This task belongs to an older version of your plan.")
    check_version(x, body.version)
    event = None
    if body.scheduled_date and body.scheduled_date != x.scheduled_date:
        new_week = (body.scheduled_date - v.start_date).days // 7 + 1  # type: ignore[union-attr]
        if new_week < 1:
            raise api_error(422, "BAD_DATE", "Choose a date within your plan.")
        week_load = db.scalar(select(func.coalesce(func.sum(PlanTask.estimated_minutes), 0)).where(
            PlanTask.plan_version_id == v.id, PlanTask.week_number == new_week, PlanTask.id != x.id)) or 0  # type: ignore[union-attr]
        t = db.get(CareerTransition, plan.transition_id)  # type: ignore[union-attr]
        if week_load + x.estimated_minutes > t.weekly_hours * 60:  # type: ignore[union-attr]
            raise api_error(409, "CAPACITY_EXCEEDED", "That week is already full. Pick another week or regenerate the plan.")
        x.scheduled_date, x.week_number = body.scheduled_date, new_week
        x.day_number = (body.scheduled_date - v.start_date).days % 7 + 1  # type: ignore[union-attr]
        event = "rescheduled"
    if body.status and body.status != x.status:
        event = {"completed": "completed", "paused": "paused", "skipped": "skipped"}.get(body.status, "reopened" if x.status == "completed" else "resumed")
        x.status = body.status
        x.completed_at = utcnow() if body.status == "completed" else None
        if body.status == "completed" and x.task_type == "lesson" and x.skill_id:
            remaining = db.scalar(select(func.count(PlanTask.id)).where(PlanTask.plan_version_id == v.id, PlanTask.skill_id == x.skill_id,  # type: ignore[union-attr]
                                                                         PlanTask.task_type == "lesson", PlanTask.status != "completed"))
            if remaining == 0:  # course finished: record it, but it does not change assessed proficiency
                db.add(SkillEvidence(workspace_id=ctx.workspace_id, skill_id=x.skill_id, evidence_type="course_completion",
                                     source_ref=x.resource_id, confidence=0.2, methodology="lesson-tasks-completed",
                                     excerpt="All study sessions completed. Take the checkpoint quiz to update your assessed level."))
        if body.status == "completed" and x.task_type == "project" and x.project_id:
            p = db.get(Project, x.project_id)
            if p and p.status == "suggested":
                p.status, p.started_at = "in_progress", utcnow()
    if event:
        db.add(TaskCompletion(workspace_id=ctx.workspace_id, task_id=x.id, event=event, minutes_spent=body.minutes_spent, note=body.note))
    db.commit()
    return task_out(x, {x.resource_id: db.get(LearningResource, x.resource_id)} if x.resource_id else {})


