def project_out(p: Project, evidence: list[ProjectEvidence]) -> dict:
    return {"id": p.id, "title": p.title, "problem_statement": p.problem_statement, "required_skills": p.required_skills,
            "milestones": p.milestones, "deliverables": p.deliverables, "rubric": p.rubric, "resume_evidence": p.resume_evidence,
            "rationale": p.rationale, "status": p.status, "repo_url": p.repo_url,
            "evidence": [{"id": e.id, "kind": e.kind, "content": e.content, "url": e.url, "rubric_scores": e.rubric_scores,
                          "score": e.score, "created_at": e.created_at.isoformat()} for e in evidence]}


@router.get("/transitions/{transition_id}/projects")
def list_projects(transition_id: str, db: DB, ctx: CtxDep) -> list[dict]:
    t = get_owned(db, CareerTransition, transition_id, ctx.workspace_id, "Career goal")
    if not db.scalar(select(Project.id).where(Project.transition_id == t.id)):
        gaps = [g["skill_id"] for g in skill_gaps(db, t)["items"] if g["gap"] > 0]
        proj_svc.ensure_projects(db, t, gaps)
        db.commit()
    out = []
    for p in db.scalars(select(Project).where(Project.transition_id == t.id).order_by(Project.created_at)):
        ev = list(db.scalars(select(ProjectEvidence).where(ProjectEvidence.project_id == p.id).order_by(ProjectEvidence.created_at)))
        out.append(project_out(p, ev))
    return out


class ProjectPatch(BaseModel):
    status: Literal["suggested", "in_progress", "completed", "dropped"] | None = None
    repo_url: str | None = Field(default=None, max_length=2000, pattern=r"^https?://")
    milestone_index: int | None = Field(default=None, ge=0, le=20)
    milestone_done: bool | None = None


@router.patch("/projects/{project_id}")
def update_project(project_id: str, body: ProjectPatch, db: DB, ctx: CtxDep) -> dict:
    p = get_owned(db, Project, project_id, ctx.workspace_id, "Project")
    if body.status:
        p.status = body.status
        p.started_at = p.started_at or (utcnow() if body.status == "in_progress" else None)
        p.completed_at = utcnow() if body.status == "completed" else None
    if body.repo_url is not None:
        p.repo_url = body.repo_url
    if body.milestone_index is not None and body.milestone_done is not None:
        if body.milestone_index >= len(p.milestones):
            raise api_error(422, "BAD_MILESTONE", "No such milestone.")
        ms = [dict(m) for m in p.milestones]
        ms[body.milestone_index]["done"] = body.milestone_done
        p.milestones = ms
    db.commit()
    return project_out(p, list(db.scalars(select(ProjectEvidence).where(ProjectEvidence.project_id == p.id))))


class EvidenceIn(BaseModel):
    kind: Literal["link", "note", "rubric_self_assessment"]
    content: str | None = Field(default=None, max_length=4000)
    url: str | None = Field(default=None, max_length=2000, pattern=r"^https?://")
    rubric_scores: dict[str, int] | None = None


@router.post("/projects/{project_id}/evidence", status_code=201)
def add_evidence(project_id: str, body: EvidenceIn, db: DB, ctx: CtxDep) -> dict:
    p = get_owned(db, Project, project_id, ctx.workspace_id, "Project")
    score = None
    if body.kind == "rubric_self_assessment":
        if not body.rubric_scores:
            raise api_error(422, "RUBRIC_REQUIRED", "Score each rubric criterion from 1 to 4.")
        score = proj_svc.rubric_score(body.rubric_scores)
        for sid in p.required_skills:
            db.add(SkillEvidence(workspace_id=ctx.workspace_id, skill_id=sid, evidence_type="project", source_ref=p.id, score=score,
                                 confidence=0.35, methodology="project-rubric-self-assessment", excerpt=p.title))
    db.add(ProjectEvidence(workspace_id=ctx.workspace_id, project_id=p.id, kind=body.kind, content=body.content, url=body.url,
                           rubric_scores=body.rubric_scores, score=score))
    db.commit()
    return project_out(p, list(db.scalars(select(ProjectEvidence).where(ProjectEvidence.project_id == p.id))))
