import { useMutation, useQuery } from "@tanstack/react-query";
import { ExternalLink } from "lucide-react";
import { useState } from "react";
import { Link } from "react-router-dom";
import { api, errorText, patch, post } from "@/lib/api";
import { useActiveTransition, useRefreshAll } from "@/lib/hooks";
import type { Plan, Task } from "@/lib/types";
import { Alert, Badge, Button, Card, CardTitle, Empty, PageHeader, Progress, Spinner, cn, statusTone } from "@/components/ui";

const TYPE_TONE: Record<string, "brand" | "good" | "warn" | "neutral"> = { lesson: "brand", exercise: "neutral", quiz: "warn", milestone: "good", project: "good", revision: "neutral" };

export function PlanPage() {
  const { transition: t } = useActiveTransition();
  const refresh = useRefreshAll();
  const plan = useQuery({ queryKey: ["plan", t?.id], queryFn: () => api<Plan | null>(`/transitions/${t!.id}/plan`), enabled: !!t });
  const gen = useMutation({ mutationFn: (scope: string) => post<Plan>(`/transitions/${t!.id}/plan`, { scope, reason: scope === "full" ? "Generated by you" : "Focus on mandatory skills" }), onSuccess: refresh });
  const applyAlt = useMutation({
    mutationFn: async (alt: Plan["feasibility"]["alternatives"][number]) => {
      if (alt.type === "extend_deadline") await patch(`/transitions/${t!.id}`, { deadline: alt.deadline });
      if (alt.type === "increase_hours") await patch(`/transitions/${t!.id}`, { weekly_hours: alt.weekly_hours });
      return post(`/transitions/${t!.id}/plan`, { scope: alt.type === "reduce_scope" ? "mandatory_only" : "full", reason: `Applied option: ${alt.text}` });
    },
    onSuccess: refresh,
  });
  const pauseResume = useMutation({ mutationFn: (op: string) => post(`/transitions/${t!.id}/plan/${op}`), onSuccess: refresh });

  if (!t) return <Empty title="Create a career goal first" />;
  if (plan.isLoading) return <Spinner />;
  const p = plan.data;
  if (!p) return (
    <>
      <PageHeader title="Learning plan" />
      <Empty title="No plan yet" action={<Button onClick={() => gen.mutate("full")} loading={gen.isPending}>Generate my plan</Button>}>
        Plans made before the assessment are provisional. For the most accurate plan, <Link className="underline" to="/assessment">take the assessment</Link> first.
      </Empty>
      {gen.isError && <div className="mt-3"><Alert tone="bad">{errorText(gen.error)}</Alert></div>}
    </>
  );

  const weeks = new Map<number, Task[]>();
  p.tasks.forEach((x) => weeks.set(x.week, [...(weeks.get(x.week) ?? []), x]));
  return (
    <>
      <PageHeader title="Learning plan" actions={<>
        <Button variant="outline" onClick={() => pauseResume.mutate(p.plan_status === "paused" ? "resume" : "pause")} loading={pauseResume.isPending}>{p.plan_status === "paused" ? "Resume" : "Pause"}</Button>
        <Button onClick={() => gen.mutate(p.summary.scope)} loading={gen.isPending}>Regenerate</Button>
      </>}>
        Version {p.version} <Badge tone={statusTone(p.status)}>{p.status}</Badge> · {p.summary.total_hours} h over {p.weeks.length} weeks · {p.reason}
      </PageHeader>
      {p.status === "provisional" && <div className="mb-4"><Alert tone="warn" title="Provisional plan">{p.summary.status_note} <Link className="underline" to="/assessment">Take the assessment</Link>.</Alert></div>}
      {p.plan_status === "paused" && <div className="mb-4"><Alert tone="warn">This plan is paused. Resuming reschedules the remaining work from today and keeps everything you completed.</Alert></div>}
      {p.feasibility.conflict && (
        <div className="mb-4"><Alert tone="bad" title="Deadline conflict">
          <p>{p.feasibility.message}</p>
          <div className="mt-2 flex flex-wrap gap-2">{p.feasibility.alternatives.map((a) => (
            <Button key={a.type} size="sm" variant="outline" onClick={() => applyAlt.mutate(a)} loading={applyAlt.isPending}>{a.text}{a.type === "reduce_scope" && a.fits === false ? " (still tight)" : ""}</Button>
          ))}</div>
        </Alert></div>
      )}
      {[gen, applyAlt, pauseResume].some((m) => m.isError) && <div className="mb-4"><Alert tone="bad">{errorText(gen.error ?? applyAlt.error ?? pauseResume.error)}</Alert></div>}

      <div className="grid gap-4 lg:grid-cols-3">
        <Card className="lg:col-span-2">
          <CardTitle>Target outcomes</CardTitle>
          <ul className="grid gap-2 sm:grid-cols-2 text-sm">{p.summary.skills.map((s) => (
            <li key={s.skill_id} className="rounded-lg border border-line p-2">
              <p className="font-medium">{s.name} <Badge tone={s.importance === "mandatory" ? "brand" : "neutral"}>{s.importance}</Badge></p>
              <p className="text-xs text-muted">{Math.round(s.initial)} ({s.basis}) → {s.target} · {Math.round(s.minutes / 60)} h{s.resource ? ` · ${s.resource}` : ""}</p>
            </li>
          ))}</ul>
          {p.summary.professional_skills.length > 0 && <p className="mt-2 text-xs text-muted">Also practised through interviews and projects: {p.summary.professional_skills.map((s) => s.name).join(", ")}.</p>}
        </Card>
        <Card>
          <CardTitle>Progress</CardTitle>
          <Progress value={p.progress.percent} label="Plan progress" />
          <p className="mt-2 text-sm">{Math.round(p.progress.completed_minutes / 60)} of {Math.round(p.progress.total_minutes / 60)} hours done</p>
          <p className="text-xs text-muted">Expected finish {p.feasibility.end_date}{p.feasibility.deadline ? ` · deadline ${p.feasibility.deadline}` : ""}</p>
          {p.versions && p.versions.length > 1 && (
            <details className="mt-3 text-xs"><summary className="cursor-pointer text-muted">Version history</summary>
              <ul className="mt-1 space-y-1">{p.versions.map((v) => <li key={v.id}>v{v.version} · {v.status} · {v.reason}</li>)}</ul></details>
          )}
        </Card>
      </div>

      <div className="mt-4 space-y-3">
        {[...weeks.entries()].sort(([a], [b]) => a - b).map(([w, tasks]) => {
          const info = p.weeks.find((x) => x.week === w);
          return (
            <details key={w} open={w <= 1 || (w > 0 && tasks.some((x) => x.status !== "completed") && w === Math.min(...[...weeks.keys()].filter((k) => k > 0 && weeks.get(k)!.some((x) => x.status !== "completed"))))}
              className="rounded-xl border border-line bg-surface">
              <summary className="flex cursor-pointer flex-wrap items-center gap-2 p-4">
                <span className="font-semibold">{w === 0 ? "Completed earlier" : `Week ${w}`}</span>
                {info && <span className="text-xs text-muted">{info.start_date} · {Math.round(info.planned_minutes / 6) / 10} of {info.capacity_minutes / 60} h · {info.objectives.join("; ")}</span>}
              </summary>
              <ul className="divide-y divide-line border-t border-line">{tasks.map((x) => <TaskRow key={x.id} task={x} />)}</ul>
            </details>
          );
        })}
      </div>
    </>
  );
}

function TaskRow({ task: x }: { task: Task }) {
  const refresh = useRefreshAll();
  const [why, setWhy] = useState(false);
  const upd = useMutation({ mutationFn: (status: string) => patch(`/tasks/${x.id}`, { status, version: x.version }), onSuccess: refresh });
  const done = x.status === "completed";
  return (
    <li className="flex flex-wrap items-start gap-3 p-3 text-sm">
      <input type="checkbox" className="mt-1 size-4" checked={done} disabled={x.carried_over || upd.isPending} aria-label={`Mark ${x.title} complete`}
        onChange={() => upd.mutate(done ? "pending" : "completed")} />
      <div className="min-w-0 flex-1">
        <p className={cn("font-medium", done && "text-muted line-through")}>{x.title}</p>
        <p className="text-xs text-muted">{x.date} · {x.minutes} min · <Badge tone={TYPE_TONE[x.type]}>{x.type}</Badge> {x.status !== "pending" && x.status !== "completed" && <Badge tone="warn">{x.status}</Badge>}</p>
        <p className="mt-1 text-xs">{x.description}</p>
        {x.resource && (
          <a className="mt-1 inline-flex items-center gap-1 text-xs text-brand underline" href={x.resource.url} target="_blank" rel="noreferrer noopener">
            {x.resource.title} ({x.resource.provider}) <ExternalLink className="size-3" aria-hidden /><Badge tone={statusTone(x.resource.verification_status)}>{x.resource.verification_status}</Badge>
          </a>
        )}
        {why && <p className="mt-1 rounded bg-bg p-2 text-xs text-muted">Why: {x.rationale} Done when: {x.criteria}</p>}
        {upd.isError && <p className="text-xs text-bad">{errorText(upd.error)}</p>}
      </div>
      <div className="flex gap-1">
        <Button size="sm" variant="ghost" onClick={() => setWhy((v) => !v)} aria-expanded={why}>Why?</Button>
        {x.type === "quiz" && x.skill_id && !done && <Link to={`/assessment?skill=${x.skill_id}`}><Button size="sm" variant="subtle">Take quiz</Button></Link>}
        {!done && !x.carried_over && <Button size="sm" variant="ghost" onClick={() => upd.mutate(x.status === "paused" ? "pending" : "paused")}>{x.status === "paused" ? "Resume" : "Pause"}</Button>}
        {!done && !x.carried_over && <Button size="sm" variant="ghost" onClick={() => upd.mutate("skipped")}>Skip</Button>}
      </div>
    </li>
  );
}
